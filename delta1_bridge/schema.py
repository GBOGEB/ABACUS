"""Shared DMAIC metrics schema for the DELTA_1 federation.

Both repos already publish the *same* JSON shape, regenerated by their
``dmaic-commit-metrics.yml`` workflow:

  * GBOGEB/CODEX  -> docs/api/metrics.json
  * GBOGEB/ABACUS -> docs/api/dmaic_metrics.json

Historically each repo validated (or did not validate) this feed on its own.
This module gives the federation a single validator so the schema cannot drift
silently between publishers. It is intentionally permissive about extra keys
(forward-compatible) and strict about the keys dashboards/badges depend on.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

# Keys every federation metrics feed must expose (consumed by README badges,
# dashboards and the drift monitor).
DMAIC_METRICS_REQUIRED_KEYS: tuple[str, ...] = (
    "timestamp",
    "sha",
    "quality_score",
    "total_commits",
    "python_files",
    "test_files",
    "total_loc",
    "workflows",
    "phase_scores",
)

_NUMERIC_KEYS: tuple[str, ...] = (
    "quality_score",
    "total_commits",
    "python_files",
    "test_files",
    "total_loc",
    "workflows",
)

_PHASE_REQUIRED = ("files", "score", "weight")


def validate_metrics(data: Mapping[str, Any]) -> list[str]:
    """Return a list of human-readable schema issues (empty list == valid).

    Does not raise: callers decide whether issues are fatal (CI) or advisory.
    """
    issues: list[str] = []

    if not isinstance(data, Mapping):
        return [f"metrics payload must be a mapping, got {type(data).__name__}"]

    for key in DMAIC_METRICS_REQUIRED_KEYS:
        if key not in data:
            issues.append(f"missing required key: {key}")

    for key in _NUMERIC_KEYS:
        if key in data and not isinstance(data[key], (int, float)):
            issues.append(
                f"key '{key}' must be numeric, got {type(data[key]).__name__}"
            )

    if "quality_score" in data and isinstance(data["quality_score"], (int, float)):
        if not 0 <= float(data["quality_score"]) <= 100:
            issues.append("quality_score must be within [0, 100]")

    phases = data.get("phase_scores")
    if phases is not None:
        if not isinstance(phases, Mapping):
            issues.append("phase_scores must be a mapping")
        else:
            for name, body in phases.items():
                if not isinstance(body, Mapping):
                    issues.append(f"phase_scores['{name}'] must be a mapping")
                    continue
                for sub in _PHASE_REQUIRED:
                    if sub not in body:
                        issues.append(f"phase_scores['{name}'] missing '{sub}'")

    return issues


def load_and_validate_metrics(path: str | Path) -> dict[str, Any]:
    """Load a metrics JSON file and return a structured validation result.

    Returns a dict: {path, found, valid, issues, data}.
    """
    p = Path(path)
    if not p.is_file():
        return {
            "path": str(p),
            "found": False,
            "valid": False,
            "issues": [f"metrics file not found: {p}"],
            "data": None,
        }
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        return {
            "path": str(p),
            "found": True,
            "valid": False,
            "issues": [f"could not parse JSON: {exc}"],
            "data": None,
        }

    issues = validate_metrics(data)
    return {
        "path": str(p),
        "found": True,
        "valid": not issues,
        "issues": issues,
        "data": data,
    }
