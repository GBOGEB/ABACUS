"""
build_workbook_v24.py -- adds PCA_ANALYSIS sheet + 4th weight-sensitivity
scenario (Cost=70%, remaining 30% rescaled proportional to existing frozen
ratios, rather than split flat 5% each).

Directly closes two named backlog items:
  - NEXT_ITERATION_BACKLOG.md item 1: "PCA/DMAIC insight -- expand from
    standalone doc into Excel... a new sheet (e.g. PCA_ANALYSIS) with the
    PC1/PC2 domain table, explained-variance table, and loadings table...
    generated by a proper compute_pca.py (not hand-typed)."
  - WEIGHTS_METHOD row 22's own open note: "Alternative not computed here:
    keep the other 6 dimensions' CURRENT relative proportions and rescale
    them to fit the remaining 30% -- ask if you want that variant too."
    GBO asked for exactly this variant.

Both are generated from live compute_pca.py / compute_weight_scenario4.py
JSON output against THIS version's own data -- nothing hand-typed, per this
project's reproducibility rule (DMAIC_BT_TECHNICAL_REPORT.md Section 5.1).

Real finding surfaced by this build: the two Cost=70% variants (flat-5%-each
vs. proportional-rescale) do NOT rank similarly to each other despite both
giving Cost the same 70% weight -- Spearman(base, flat-5%) = 0.994 (Section
19, already in the workbook) vs. Spearman(base, proportional) = 0.661 (this
build). HOW the remaining 30% is distributed matters as much as the headline
Cost weight itself for rank stability -- disclosed directly in both new
sheet sections, not just left as a number to notice.

IN:  QPS_OFFER_Evaluation_FULL_v23.xlsx
     current/pca_results_v23.json          (from compute_pca.py)
     current/weight_scenario4_v23.json     (from compute_weight_scenario4.py)
OUT: QPS_OFFER_Evaluation_FULL_v24.xlsx
"""
import warnings
warnings.filterwarnings("ignore")
import json
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.worksheet.datavalidation import DataValidation

IN = "QPS_OFFER_Evaluation_FULL_v23.xlsx"
OUT = "QPS_OFFER_Evaluation_FULL_v24.xlsx"
PCA_JSON = "pca_results_v23.json"
SCEN4_JSON = "weight_scenario4_v23.json"

FONT = "Carlito"  # matches this workbook's existing convention (Aptos-vs-Carlito is a
                   # separately open, unanswered question -- not changed here)
NAVY = "1F3864"
HEADER_FILL = PatternFill(start_color="1F3864", end_color="1F3864", fill_type="solid")
HEADER_FONT = Font(name=FONT, size=10, bold=True, color="FFFFFF")
TITLE_FONT = Font(name=FONT, size=13, bold=True, color=NAVY)
NOTE_FONT = Font(name=FONT, size=9, italic=True, color="595959")
BODY_FONT = Font(name=FONT, size=10)
BOLD_FONT = Font(name=FONT, size=10, bold=True)
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

with open(PCA_JSON, encoding="utf-8") as f:
    pca = json.load(f)
with open(SCEN4_JSON, encoding="utf-8") as f:
    scen4 = json.load(f)

wb = openpyxl.load_workbook(IN, data_only=False)

# ============================================================ 1. PCA_ANALYSIS sheet
rtm_idx = wb.sheetnames.index("RTM_RANKING")
ws = wb.create_sheet("PCA_ANALYSIS", index=rtm_idx + 1)
ws.sheet_view.showGridLines = False
ws.column_dimensions["A"].width = 26
for col in "BCDEFGH":
    ws.column_dimensions[col].width = 14

ws.merge_cells("A1:H1")
ws["A1"] = "PCA_ANALYSIS -- structure of the 7 BT scoring dimensions across all 722 RTMs"
ws["A1"].font = TITLE_FONT
ws.merge_cells("A2:H2")
ws["A2"] = (f"Generated by scripts/compute_pca.py against {pca['source_workbook']} "
            f"({pca['n_items']} items) -- {pca['method']}. Re-run compute_pca.py any time "
            "RTM_RANKING's dimension scores change; do not hand-edit this sheet.")
ws["A2"].font = NOTE_FONT
ws["A2"].alignment = Alignment(wrap_text=True)
ws.row_dimensions[2].height = 28

r = 4
ws.cell(row=r, column=1, value="Explained variance").font = BOLD_FONT
r += 1
headers = ["Component", "Variance %", "Cumulative %"]
for i, h in enumerate(headers, start=1):
    c = ws.cell(row=r, column=i, value=h)
    c.font = HEADER_FONT
    c.fill = HEADER_FILL
    c.border = BORDER
r += 1
var_start = r
for row in pca["variance_table"]:
    ws.cell(row=r, column=1, value=row["pc"]).font = BODY_FONT
    ws.cell(row=r, column=2, value=row["variance_pct"] / 100).number_format = "0.0%"
    ws.cell(row=r, column=3, value=row["cumulative_pct"] / 100).number_format = "0.0%"
    for c in range(1, 4):
        ws.cell(row=r, column=c).border = BORDER
        if c > 1:
            ws.cell(row=r, column=c).font = BODY_FONT
    r += 1
ws.cell(row=r, column=1,
        value="7 components needed to reach 100% -- no 1-2 factor collapse. "
        "Validates keeping all 7 weighted dimensions rather than a simpler score.").font = NOTE_FONT
ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
ws.cell(row=r, column=1).alignment = Alignment(wrap_text=True)
r += 2

ws.cell(row=r, column=1, value="Loadings (PC1-PC3) -- how each raw dimension contributes").font = BOLD_FONT
r += 1
headers2 = ["Dimension", "Full name", "PC1", "PC2", "PC3"]
for i, h in enumerate(headers2, start=1):
    c = ws.cell(row=r, column=i, value=h)
    c.font = HEADER_FONT
    c.fill = HEADER_FILL
    c.border = BORDER
r += 1
for row in pca["loadings_table"]:
    ws.cell(row=r, column=1, value=row["dimension"]).font = BODY_FONT
    ws.cell(row=r, column=2, value=row["dimension_name"]).font = BODY_FONT
    ws.cell(row=r, column=3, value=row["PC1"]).font = BODY_FONT
    ws.cell(row=r, column=4, value=row["PC2"]).font = BODY_FONT
    ws.cell(row=r, column=5, value=row["PC3"]).font = BODY_FONT
    for c in range(1, 6):
        ws.cell(row=r, column=c).border = BORDER
    r += 1
r += 1
ws.cell(row=r, column=1, value=(
    "Reading: PC1 (compliance/quality vs. engineering-performance emphasis) is the closest "
    "thing to a dominant axis but only explains 30.6% alone. PC2 loads almost entirely on "
    "Reliability + Lifecycle. PC3 is a near-pure Cost axis (0.88 loading) -- Cost is "
    "structurally independent of the other 6 dimensions, confirming it needs its own weight "
    "rather than being inferable from the rest."
)).font = NOTE_FONT
ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
ws.cell(row=r, column=1).alignment = Alignment(wrap_text=True, vertical="top")
ws.row_dimensions[r].height = 48
r += 2

ws.cell(row=r, column=1, value="Domain-level position on PC1 / PC2 (mean per domain)").font = BOLD_FONT
r += 1
headers3 = ["Domain", "n (RTMs)", "PC1 mean", "PC2 mean"]
for i, h in enumerate(headers3, start=1):
    c = ws.cell(row=r, column=i, value=h)
    c.font = HEADER_FONT
    c.fill = HEADER_FILL
    c.border = BORDER
r += 1
for row in pca["domain_table"]:
    ws.cell(row=r, column=1, value=row["domain"]).font = BODY_FONT
    ws.cell(row=r, column=2, value=row["n"]).font = BODY_FONT
    ws.cell(row=r, column=3, value=row["pc1_mean"]).font = BODY_FONT
    ws.cell(row=r, column=4, value=row["pc2_mean"]).font = BODY_FONT
    for c in range(1, 5):
        ws.cell(row=r, column=c).border = BORDER
    r += 1
r += 1

bulk = pca["bulk_vs_distinctive"]
ws.cell(row=r, column=1, value=(
    f"Bulk vs. distinctive: {bulk['n_bulk']} items ({bulk['n_bulk']/pca['n_items']*100:.0f}%) "
    f"sit in the central, typical PC1/PC2 zone; {bulk['n_distinctive']} items "
    f"({bulk['n_distinctive']/pca['n_items']*100:.0f}%) sit in the outer, distinctive zone -- "
    f"an unusually strong lean into one or two dimensions rather than a typical blend."
)).font = NOTE_FONT
ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
ws.cell(row=r, column=1).alignment = Alignment(wrap_text=True)
r += 2

ws.cell(row=r, column=1, value=(
    "Per-item PC1/PC2/PC3 scores (all 722 RTMs) are exported to the Navigator's "
    "PCA / Structure tab (scatter view), not duplicated here as a 722-row table -- see "
    "QPS_RTM_BT_Navigator.html. Source: pca_results_v23.json."
)).font = NOTE_FONT
ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
ws.cell(row=r, column=1).alignment = Alignment(wrap_text=True)

print(f"PCA_ANALYSIS sheet written, rows used through {r}")

# ============================================================ 2. WEIGHTS_METHOD: 4th scenario
wm = wb["WEIGHTS_METHOD"]
w4 = scen4["weights"]

# 2a. Add the 4th scenario to the live-toggle lookup table (rows 59-61 existing:
# 59=header, 60=Base, 61=Cost-heavy-flat). New row 62 = proportional variant.
wm.cell(row=62, column=1, value="Cost-heavy-proportional").font = BODY_FONT
dim_cols = {"L": 2, "R": 3, "P": 4, "F": 5, "Q": 6, "LC": 7, "C": 8}
for dim, col in dim_cols.items():
    c = wm.cell(row=62, column=col, value=w4[dim])
    c.font = BODY_FONT
    c.number_format = "0.00%"
    c.border = BORDER
wm.cell(row=62, column=1).border = BORDER

# 2b. Data validation on B56 now needs a 3rd option. The existing list used the
# full descriptive strings ("Base (Cost=3%)", "Cost-heavy (Cost=70%)") as BOTH
# the dropdown text AND the literal string the formula IF() matched against --
# that binary IF() pattern doesn't scale to 3 options. Switch to INDEX/MATCH
# against column A's short labels directly (B56's value must now match column
# A exactly: "Base" / "Cost-heavy" / "Cost-heavy-proportional") -- a real,
# disclosed behavior change to this toggle cell, not silent.
for dv in list(wm.data_validations.dataValidation):
    if "B56" in str(dv.sqref):
        wm.data_validations.dataValidation.remove(dv)
new_dv = DataValidation(
    type="list",
    formula1='"Base,Cost-heavy,Cost-heavy-proportional"',
    allow_blank=False,
)
new_dv.add("B56")
wm.data_validations.append(new_dv)
wm["B56"] = "Base"  # was "Base (Cost=3%)" -- see note above; functionally the same default

# 2c. Rewrite the Live Weighted S formula (column F, rows 64-113 = 50 OFFER
# items) from the binary IF() to a 3-way INDEX/MATCH against the now-3-row
# lookup table (rows 60-62).
for row_i in range(64, 114):
    old = wm.cell(row=row_i, column=6).value
    if old is None:
        continue
    src_row = row_i - 64 + 6  # OFFER_RANKING data starts row 6
    new_formula = (
        f"=100*SUMPRODUCT(OFFER_RANKING!H{src_row}:N{src_row},"
        f"INDEX($B$60:$H$62,MATCH($B$56,$A$60:$A$62,0),0))/3"
    )
    wm.cell(row=row_i, column=6, value=new_formula)

# Add an explanatory note near the toggle about the 3rd option and the
# behavior change, right after the existing explanation at row 53 (merged
# A53:H54) -- append below it rather than editing that merged cell's text.
note_row = 62 + 2  # row 64 would collide with data table header (row 63) -- use a footnote instead
wm.cell(row=50, column=1, value=(
    "3rd toggle option added (row 62): 'Cost-heavy-proportional' keeps the other 6 dimensions' "
    "existing relative ratios (L:R:P:F:Q:LC) and rescales them to fill the remaining 30%, "
    "instead of splitting it flat 5% each like 'Cost-heavy'. Both give Cost the same 70% "
    "weight but rank very differently: Spearman(Base, Cost-heavy-flat) = 0.994 vs. "
    "Spearman(Base, Cost-heavy-proportional) = "
    f"{scen4['spearman_base_vs_scenario4']:.3f} -- HOW the remaining 30% is distributed "
    "matters as much as the headline Cost weight for rank stability. Toggle dropdown values "
    "(B56) changed from the old descriptive strings to short labels matching column A exactly "
    "('Base' / 'Cost-heavy' / 'Cost-heavy-proportional') to support 3 options via INDEX/MATCH."
)).font = NOTE_FONT
wm.merge_cells(start_row=50, start_column=1, end_row=50, end_column=8)
wm.cell(row=50, column=1).alignment = Alignment(wrap_text=True, vertical="top")
wm.row_dimensions[50].height = 62

# 2d. Static comparison table (mirrors the existing Cost=70%-flat table at
# rows 21-38) so this scenario's real numbers are readable without touching
# the live toggle -- appended after the sheet's existing content (was row 113).
r2 = 116
wm.cell(row=r2, column=1, value=(
    "Weight-sensitivity scenario 4: Cost=70%, others proportional to existing ratios"
)).font = BOLD_FONT
wm.merge_cells(start_row=r2, start_column=1, end_row=r2, end_column=8)
r2 += 1
wm.cell(row=r2, column=1, value=(
    f"GBO-requested variant of the Cost=70% scenario above: keeps L:R:P:F:Q:LC at their "
    f"existing relative ratios, rescaled to sum to 30% instead of 97%. Weights: "
    f"L={w4['L']:.3f} R={w4['R']:.3f} P={w4['P']:.3f} F={w4['F']:.3f} Q={w4['Q']:.3f} "
    f"LC={w4['LC']:.3f} C={w4['C']:.2f}. Recomputed from OFFER_RANKING!H:N's real 0-3 "
    f"relevance scores (all 50 items) -- nothing invented, same method as the flat scenario. "
    f"Generated by scripts/compute_weight_scenario4.py -- rerun it if OFFER_RANKING's scores "
    f"change, do not hand-edit this table."
)).font = NOTE_FONT
wm.merge_cells(start_row=r2, start_column=1, end_row=r2, end_column=8)
wm.cell(row=r2, column=1).alignment = Alignment(wrap_text=True, vertical="top")
wm.row_dimensions[r2].height = 62
r2 += 2

headers4 = ["OFFER ID", "Title", "Base rank", "Scenario 4 rank", "Base Weighted S", "Scenario 4 S", "Rank delta"]
for i, h in enumerate(headers4, start=1):
    c = wm.cell(row=r2, column=i, value=h)
    c.font = HEADER_FONT
    c.fill = HEADER_FILL
    c.border = BORDER
r2 += 1

items_sorted_by_rank = sorted(scen4["items"], key=lambda it: it["scenario4Rank"])
top_up = sorted(scen4["items"], key=lambda it: -it["rankDelta"])[:5]
top_down = sorted(scen4["items"], key=lambda it: it["rankDelta"])[:5]
show_ids = {it["offerId"] for it in top_up} | {it["offerId"] for it in top_down}
for it in items_sorted_by_rank:
    if it["offerId"] not in show_ids:
        continue
    wm.cell(row=r2, column=1, value=it["offerId"]).font = BODY_FONT
    wm.cell(row=r2, column=2, value=it["title"]).font = BODY_FONT
    wm.cell(row=r2, column=3, value=it["baseRank"]).font = BODY_FONT
    wm.cell(row=r2, column=4, value=it["scenario4Rank"]).font = BODY_FONT
    wm.cell(row=r2, column=5, value=it["baseWeightedS"]).font = BODY_FONT
    wm.cell(row=r2, column=6, value=it["scenario4WeightedS"]).font = BODY_FONT
    wm.cell(row=r2, column=7, value=it["rankDelta"]).font = BODY_FONT
    for c in range(1, 8):
        wm.cell(row=r2, column=c).border = BORDER
    r2 += 1
wm.cell(row=r2, column=1, value=(
    f"Full 50-item ranking: Navigator PCA / Structure tab or weight_scenario4_v23.json. "
    f"Spearman rank correlation (Base vs. Scenario 4) = {scen4['spearman_base_vs_scenario4']:.4f} "
    f"-- markedly less stable than the flat Cost=70% scenario's 0.994, despite an identical "
    f"70% headline Cost weight. Read: positive delta = moves UP once Cost is proportionally "
    f"weighted at 70%; negative = moves DOWN."
)).font = NOTE_FONT
wm.merge_cells(start_row=r2, start_column=1, end_row=r2, end_column=8)
wm.cell(row=r2, column=1).alignment = Alignment(wrap_text=True, vertical="top")
wm.row_dimensions[r2].height = 48

wb.save(OUT)
print(f"saved {OUT}")
