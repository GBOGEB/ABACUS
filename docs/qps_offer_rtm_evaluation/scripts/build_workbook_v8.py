"""
build_workbook_v8.py -- Phase 8: fixes the DELIVERABLES sheet's column F
("Fulfilment / Evidence / Measurability"), flagged by GBO as "LAZY": every
row shared the same fixed opening clause and only 16 distinct combinations
existed across the 50 OFFER items (9 rows had literally nothing but the
generic opener, no differentiation at all). This was inherited from an
earlier phase (not generated by any build_workbook_*.py in this repo) and
carried forward unchanged through v5/v6/v7 -- so it never got the same
per-row rule-based treatment RTM_RANKING's evidence column got.

Fix, two parts:
  1. A real RTM cross-reference clause per OFFER item, pulled from
     OFFER_CANONICAL.primary_rtm_ids -- this is the "the fulfilment should
     be linked here" ask: instead of re-describing evidence generically,
     point at the actual linked RTM(s), where the real per-item evidence
     already lives (RTM_RANKING/RTM_LOOKUP), so nothing is duplicated.
  2. An EPIC-keyed evidence-type descriptor, rule-derived from the
     OFFER_CANONICAL.EPIC field (already-curated data, not invented) against
     a small controlled vocabulary. That vocabulary is added ONCE, to
     TAXONOMY, as the canonical definition; DELIVERABLES!F reuses the exact
     same phrase rather than restating it -- single source, no duplicate
     definitions, per GBO's "SSOT and no duplications" ask.

Disclosed in a DELIVERABLES sheet note, same convention as every other
rule-derived column in this workbook.
"""
import warnings, re
warnings.filterwarnings("ignore")
import openpyxl
from openpyxl.styles import Font, Alignment

IN = "QPS_OFFER_Evaluation_FULL_v7.xlsx"
OUT = "QPS_OFFER_Evaluation_FULL_v8.xlsx"

wb = openpyxl.load_workbook(IN, data_only=False)

# ---- EPIC -> evidence-type vocabulary (canonical, defined once, reused) ---
EPIC_EVIDENCE = {
    "SYSTEM_PERFORMANCE":     "Calculation/model plus calibrated measurement or witnessed test against the stated performance criteria.",
    "PROCESS_DESIGN":         "Process/design documentation review (P&ID, mass/energy balance, or equivalent) against the stated design criteria.",
    "MECHANICAL_DESIGN":      "Design/fabrication documentation review (drawings, material certificates, weld/NDT records) against the stated criteria.",
    "SOFTWARE":               "Functional design/configuration review and interface or sequence demonstration (FAT/SAT) against the stated behaviour.",
    "CONTROL_SYSTEM":         "Functional design/configuration review and interface or sequence demonstration (FAT/SAT) against the stated behaviour.",
    "INFRASTRUCTURE":         "Design documentation review plus site or structural verification against the stated criteria.",
    "OPERATIONS_MAINTENANCE": "Procedure/plan document review plus RAM or maintenance substantiation.",
    "QUALITY_RISK":           "Document review, audit, or a traceable QC/risk-register record against the stated criteria.",
    "COMMERCIAL":             "Document review and traceability/approval-status confirmation (a governance or commercial deliverable, not a technical test).",
    "PROJECT_EXECUTION":      "Document review and traceability/approval-status confirmation (a governance or commercial deliverable, not a technical test).",
}
EPIC_FONT = Font(name="Carlito", italic=True, color="5B7FA6")   # same "rule-derived" blue used elsewhere
LINK_FONT = Font(name="Carlito", color="222222")
CELL_ALIGN = Alignment(vertical="top", wrap_text=True)

def rtm_link_clause(rtm_ids_raw):
    if not rtm_ids_raw or str(rtm_ids_raw).strip().lower() in ("none", ""):
        return "No RTM crosswalk anchor for this item — its evidence basis is the OFFER text response itself (see Explicit Deliverable / Proof, this row)."
    ids = str(rtm_ids_raw).strip()
    # count distinct anchors (handles both "RTM-019..RTM-022" ranges and "RTM-341; RTM-343..RTM-344" lists)
    n_tokens = len([t for t in re.split(r";", ids) if t.strip()])
    plural = "RTMs" if (n_tokens > 1 or ".." in ids) else "RTM"
    return f"Evidenced via linked {plural} {ids} — see RTM Ranking / RTM Lookup for that item's own detailed evidence criteria (not repeated here)."

# ---- pull EPIC + primary_rtm_ids per OFFER id from OFFER_CANONICAL --------
canon = wb["OFFER_CANONICAL"]
offer_meta = {}
for r in range(6, canon.max_row + 1):
    oid = canon.cell(row=r, column=1).value
    if not oid:
        continue
    offer_meta[oid] = {
        "epic": canon.cell(row=r, column=7).value,
        "rtm_ids": canon.cell(row=r, column=11).value,
    }

# ---- rewrite DELIVERABLES!F ------------------------------------------------
ws = wb["DELIVERABLES"]
n_fixed = n_no_epic = 0
for r in range(6, ws.max_row + 1):
    oid = ws.cell(row=r, column=2).value
    if not oid or oid not in offer_meta:
        continue
    meta = offer_meta[oid]
    link_clause = rtm_link_clause(meta["rtm_ids"])
    epic = (meta["epic"] or "").strip()
    epic_clause = EPIC_EVIDENCE.get(epic)
    if not epic_clause:
        n_no_epic += 1
        epic_clause = "Document review and traceability/approval-status confirmation against the stated criteria."
    cell = ws.cell(row=r, column=6, value=f"{link_clause} {epic_clause}")
    cell.font = EPIC_FONT
    cell.alignment = CELL_ALIGN
    n_fixed += 1
print(f"DELIVERABLES!F rewritten: {n_fixed} rows ({n_no_epic} with no EPIC match, used fallback)")

# widen F a bit and grow row heights to fit the longer, real text
ws.column_dimensions["F"].width = 46
import math
for r in range(6, ws.max_row + 1):
    text = ws.cell(row=r, column=6).value or ""
    d_text = ws.cell(row=r, column=5).value or ""
    lines_f = math.ceil(len(str(text)) / 58) if text else 1
    lines_d = math.ceil(len(str(d_text)) / 42) if d_text else 1
    lines = max(lines_f, lines_d, 2)
    ws.row_dimensions[r].height = max(34, lines * 13 + 8)

# ---- disclosure note on DELIVERABLES sheet ---------------------------------
last_row = ws.max_row + 2
ws.cell(row=last_row, column=1,
         value=("Column F methodology (Phase 8): rule-derived from OFFER_CANONICAL, not hand-authored "
                "per row. The first clause is a real RTM cross-reference (from primary_rtm_ids) pointing "
                "to that item's own detailed evidence in RTM_RANKING/RTM_LOOKUP -- evidence is not restated "
                "here to avoid a second, driftable copy. The second clause is picked from the EPIC-keyed "
                "vocabulary defined once in TAXONOMY ('OFFER evidence-type vocabulary') and reused verbatim "
                "here, not redefined. Shown in italic blue, the same convention used for every other "
                "rule-derived (vs. hand-reviewed) field in this workbook.")
         ).font = Font(name="Carlito", italic=True, size=10.5, color="444444")
ws.cell(row=last_row, column=1).alignment = Alignment(wrap_text=True, vertical="top")
ws.merge_cells(start_row=last_row, start_column=1, end_row=last_row, end_column=7)
ws.row_dimensions[last_row].height = 75

# ---- add the canonical vocabulary table to TAXONOMY (defined once) --------
tax = wb["TAXONOMY"]
r = tax.max_row + 3
tax.cell(row=r, column=1, value="OFFER evidence-type vocabulary (by EPIC)").font = Font(name="Carlito", size=13, bold=True, color="17365D")
r += 1
tax.cell(row=r, column=1, value="EPIC").font = Font(name="Carlito", bold=True, color="FFFFFF")
tax.cell(row=r, column=2, value="Evidence-type descriptor (canonical wording -- DELIVERABLES!F reuses this verbatim)").font = Font(name="Carlito", bold=True, color="FFFFFF")
for c in (1, 2):
    tax.cell(row=r, column=c).fill = openpyxl.styles.PatternFill("solid", fgColor="1F4E78")
r += 1
for epic, desc in EPIC_EVIDENCE.items():
    tax.cell(row=r, column=1, value=epic).font = Font(name="Carlito", bold=True)
    c2 = tax.cell(row=r, column=2, value=desc)
    c2.alignment = Alignment(wrap_text=True, vertical="top")
    tax.merge_cells(start_row=r, start_column=2, end_row=r, end_column=6)
    tax.row_dimensions[r].height = 30
    r += 1

wb.save(OUT)
print(f"saved {OUT}")
